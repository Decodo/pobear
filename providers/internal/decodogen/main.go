package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"slices"
	"sort"
	"strconv"
	"strings"
	"time"
)

const (
	irListURL = "https://storage.googleapis.com/storage/v1/b/decodo-sdk-config/o?prefix=decodo-ir-v"
	irURLFmt  = "https://storage.googleapis.com/decodo-sdk-config/decodo-ir-v%s.json"

	endpoint        = "https://data.decodo.com/v1/scrape"
	defaultTemplate = "universal"
)

var skipParams = map[string]bool{
	"target":                  true,
	"url":                     true,
	"callback_url":            true,
	"markdown":                true,
	"xhr":                     true,
	"cookies":                 true,
	"headers":                 true,
	"force_cookies":           true,
	"force_headers":           true,
	"successful_status_codes": true,
}

var optionDefaults = map[string]string{
	"headless":   "html",
	"proxy_pool": "premium",
}

var optionOrder = []string{"headless", "proxy_pool", "geo", "locale", "device_type", "page_count", "page_from", "parse"}

type ir struct {
	Version string `json:"version"`
	APIs    struct {
		WebScrapingAPI struct {
			Targets map[string]struct {
				ParameterSchema struct {
					Properties map[string]property `json:"properties"`
				} `json:"parameter_schema"`
			} `json:"targets"`
		} `json:"webScrapingApi"`
	} `json:"apis"`
}

type property struct {
	Type    string   `json:"type"`
	Enum    []any    `json:"enum"`
	Minimum *float64 `json:"minimum"`
	Maximum *float64 `json:"maximum"`
}

type option struct {
	name, typ, def string
	values         []string
	min, max       *float64
}

type template struct {
	name    string
	options []option
}

func main() {
	irPath := flag.String("ir", "", "read the IR from this file instead of fetching the latest")
	out := flag.String("out", "decodo.yaml", "output manifest path")
	flag.Parse()

	data, err := loadIR(*irPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "decodogen:", err)
		os.Exit(1)
	}
	manifest, err := generate(data)
	if err != nil {
		fmt.Fprintln(os.Stderr, "decodogen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, manifest, 0o644); err != nil { //nolint:gosec // a checked-in source file, meant to be world-readable
		fmt.Fprintln(os.Stderr, "decodogen:", err)
		os.Exit(1)
	}
}

func loadIR(path string) ([]byte, error) {
	if path != "" {
		return os.ReadFile(path) //nolint:gosec // path is the developer's own -ir flag
	}
	client := &http.Client{Timeout: 30 * time.Second}
	list, err := get(client, irListURL)
	if err != nil {
		return nil, err
	}
	var listing struct {
		Items []struct {
			Name string `json:"name"`
		} `json:"items"`
	}
	if err := json.Unmarshal(list, &listing); err != nil {
		return nil, fmt.Errorf("parse IR listing: %w", err)
	}
	var latest string
	var latestParts []int
	for _, item := range listing.Items {
		v := strings.TrimSuffix(strings.TrimPrefix(item.Name, "decodo-ir-v"), ".json")
		parts, ok := parseVersion(v)
		if ok && (latestParts == nil || slices.Compare(parts, latestParts) > 0) {
			latest, latestParts = v, parts
		}
	}
	if latest == "" {
		return nil, fmt.Errorf("no IR versions found at %s", irListURL)
	}
	return get(client, fmt.Sprintf(irURLFmt, latest))
}

func parseVersion(v string) ([]int, bool) {
	fields := strings.Split(v, ".")
	parts := make([]int, len(fields))
	for i, f := range fields {
		n, err := strconv.Atoi(f)
		if err != nil {
			return nil, false
		}
		parts[i] = n
	}
	return parts, true
}

func get(client *http.Client, url string) ([]byte, error) {
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

func generate(data []byte) ([]byte, error) {
	var schema ir
	if err := json.Unmarshal(data, &schema); err != nil {
		return nil, fmt.Errorf("parse IR: %w", err)
	}
	targets := schema.APIs.WebScrapingAPI.Targets
	if _, ok := targets[defaultTemplate]; !ok {
		return nil, fmt.Errorf("IR %s has no %q target", schema.Version, defaultTemplate)
	}

	var templates []template
	for name, t := range targets {
		props := t.ParameterSchema.Properties
		if _, ok := props["url"]; !ok {
			continue
		}
		templates = append(templates, template{name: name, options: options(props)})
	}
	sort.Slice(templates, func(i, j int) bool {
		a, b := templates[i].name, templates[j].name
		if (a == defaultTemplate) != (b == defaultTemplate) {
			return a == defaultTemplate
		}
		return a < b
	})

	var sb strings.Builder
	fmt.Fprintf(&sb, "# Code generated by providers/internal/decodogen from Decodo IR v%s; DO NOT EDIT.\n", schema.Version)
	sb.WriteString("name: decodo\n")
	fmt.Fprintf(&sb, "endpoint: %s\n", endpoint)
	sb.WriteString("auth: { type: bearer, credential: token }\n")
	sb.WriteString("headers:\n  x-integration: oss-pobear\n")
	sb.WriteString("templates:\n")
	for _, t := range templates {
		writeTemplate(&sb, t)
	}
	sb.WriteString("errors:\n")
	sb.WriteString("  - { status: 401, kind: auth }\n")
	sb.WriteString("  - { status: 429, kind: rateLimit }\n")
	sb.WriteString("response:\n")
	sb.WriteString("  status: \"$..status_code\"\n")
	sb.WriteString("  body: \"$..content\"\n")
	return []byte(sb.String()), nil
}

func options(props map[string]property) []option {
	var opts []option
	for name, p := range props {
		if skipParams[name] {
			continue
		}
		o := option{name: name, def: optionDefaults[name]}
		switch {
		case len(p.Enum) > 0:
			o.typ = "enum"
			for _, v := range p.Enum {
				o.values = append(o.values, fmt.Sprint(v))
			}
		case p.Type == "string":
			o.typ = "string"
		case p.Type == "boolean":
			o.typ = "bool"
		case p.Type == "number" || p.Type == "integer":
			o.typ = "int"
			o.min, o.max = p.Minimum, p.Maximum
		default:
			continue
		}
		opts = append(opts, o)
	}
	rank := func(name string) int {
		if i := slices.Index(optionOrder, name); i >= 0 {
			return i
		}
		return len(optionOrder)
	}
	sort.Slice(opts, func(i, j int) bool {
		ri, rj := rank(opts[i].name), rank(opts[j].name)
		if ri != rj {
			return ri < rj
		}
		return opts[i].name < opts[j].name
	})
	return opts
}

func writeTemplate(sb *strings.Builder, t template) {
	fmt.Fprintf(sb, "  - name: %s\n", t.name)
	if t.name == defaultTemplate {
		sb.WriteString("    default: true\n")
	}
	if len(t.options) > 0 {
		sb.WriteString("    options:\n")
		for _, o := range t.options {
			fields := []string{"name: " + o.name, "type: " + o.typ}
			if o.typ == "enum" {
				fields = append(fields, "values: ["+strings.Join(o.values, ", ")+"]")
			}
			if o.def != "" {
				fields = append(fields, "default: "+o.def)
			}
			if o.min != nil {
				fields = append(fields, "min: "+strconv.FormatFloat(*o.min, 'f', -1, 64))
			}
			if o.max != nil {
				fields = append(fields, "max: "+strconv.FormatFloat(*o.max, 'f', -1, 64))
			}
			fmt.Fprintf(sb, "      - { %s }\n", strings.Join(fields, ", "))
		}
	}
	sb.WriteString("    request:\n      body:\n")
	fmt.Fprintf(sb, "        target: %s\n", t.name)
	sb.WriteString("        url: \"{{ .URL }}\"\n")
	for _, o := range t.options {
		fmt.Fprintf(sb, "        %s: \"{{ .Options.%s }}\"\n", o.name, o.name)
	}
}
